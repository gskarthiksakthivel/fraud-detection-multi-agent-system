@app.post("/api/v1/analyse", response_model=AnalysisResponse, tags=["Analysis"])
async def analyse_transaction(
    request: TransactionRequest,
    current_user: dict = Depends(get_current_user)
):
    """
    Analyse a transaction through the full multi-agent pipeline.
    Returns risk assessment, fraud score, and escalation decision.
    """
    session_id = request.session_id or str(uuid.uuid4())
    is_safe, sanitised_input = validate_input(str(request.model_dump()))
    if not is_safe:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Input rejected by guardrails")

    initial_state: AgentState = {
        "transaction_id": request.transaction_id,
        "session_id": session_id,
        "transaction_data": request.model_dump(),
        "messages": [],
        "fraud_output": None,
        "compliance_output": None,
        "risk_output": None,
        "investigation_output": None,
        "escalation_output": None,
        "next_agent": "fraud_agent",
        "agents_completed": [],
        "should_escalate": False,
        "mcp_tools_called": [],
        "final_risk_level": None,
        "final_fraud_score": 0.0,
        "escalation_status": None,
        "final_summary": None,
        "audit_trail_id": None,
        "error": None,
        "processing_start_ms": time.time() * 1000,
    }

    start_time = time.time()
    try:
        final_state = await agent_graph.ainvoke(initial_state)
        await state_manager.save_state(session_id, {k: str(v) for k, v in final_state.items() if v is not None})
    except Exception as e:
        logger.error(f"[API] Graph execution failed: {e}")
        raise HTTPException(status_code=500, detail=f"Agent pipeline failed: {str(e)}")

    processing_ms = (time.time() - start_time) * 1000

    agent_decisions = []
    for agent_name in final_state.get("agents_completed", []):
        agent_decisions.append(AgentDecision(
            agent_name=agent_name,
            decision="completed",
            confidence=0.85,
            reasoning=f"{agent_name} executed successfully",
            tools_called=[t for t in final_state.get("mcp_tools_called", []) if agent_name.split("_")[0] in t]
        ))

    return AnalysisResponse(
        transaction_id=request.transaction_id,
        session_id=session_id,
        risk_level=final_state.get("final_risk_level") or RiskLevel.LOW,
        fraud_score=final_state.get("final_fraud_score") or 0.0,
        escalation_status=final_state.get("escalation_status") or EscalationStatus.RESOLVED,
        agent_decisions=agent_decisions,
        summary=final_state.get("final_summary") or "Analysis complete",
        recommendations=["Review flagged transaction", "Monitor account activity"],
        audit_trail_id=final_state.get("audit_trail_id") or str(uuid.uuid4()),
        processing_time_ms=processing_ms
    )


@app.post("/api/v1/analyse/stream", tags=["Analysis"])
async def analyse_transaction_stream(
    request: TransactionRequest,
    current_user: dict = Depends(get_current_user)
):
    """
    SSE streaming version — streams agent progress events as they complete.
    Useful for UI dashboards showing real-time agent activity.
    """
    session_id = request.session_id or str(uuid.uuid4())

    async def event_generator():
        yield f"data: {json.dumps({'event': 'started', 'session_id': session_id, 'transaction_id': request.transaction_id})}\n\n"
        await asyncio.sleep(0.1)

        agents_sequence = ["supervisor", "fraud_agent", "compliance_agent", "risk_agent", "investigation_agent", "escalation_agent"]

        initial_state: AgentState = {
            "transaction_id": request.transaction_id,
            "session_id": session_id,
            "transaction_data": request.model_dump(),
            "messages": [],
            "fraud_output": None, "compliance_output": None,
            "risk_output": None, "investigation_output": None, "escalation_output": None,
            "next_agent": "fraud_agent", "agents_completed": [],
            "should_escalate": False, "mcp_tools_called": [],
            "final_risk_level": None, "final_fraud_score": 0.0,
            "escalation_status": None, "final_summary": None,
            "audit_trail_id": None, "error": None,
            "processing_start_ms": time.time() * 1000,
        }

        try:
            async for chunk in agent_graph.astream(initial_state):
                for node_name, node_output in chunk.items():
                    event_data = {
                        "event": "agent_completed",
                        "agent": node_name,
                        "agents_completed": node_output.get("agents_completed", []),
                        "mcp_tools_called": node_output.get("mcp_tools_called", []),
                    }
                    if node_output.get("final_fraud_score"):
                        event_data["fraud_score"] = node_output["final_fraud_score"]
                    if node_output.get("final_risk_level"):
                        event_data["risk_level"] = str(node_output["final_risk_level"])
                    if node_output.get("escalation_status"):
                        event_data["escalation_status"] = str(node_output["escalation_status"])

                    yield f"data: {json.dumps(event_data)}\n\n"
                    await asyncio.sleep(0.05)

            yield f"data: {json.dumps({'event': 'completed', 'session_id': session_id})}\n\n"

        except Exception as e:
            yield f"data: {json.dumps({'event': 'error', 'message': str(e)})}\n\n"

    return StreamingResponse(event_generator(), media_type="text/event-stream")


@app.post("/api/v1/escalate", response_model=EscalationResponse, tags=["Escalation"])
async def manual_escalate(
    request: EscalationRequest,
    current_user: dict = Depends(get_current_user)
):
    """Manual escalation trigger for human reviewers."""
    return EscalationResponse(
        escalation_id=str(uuid.uuid4()),
        transaction_id=request.transaction_id,
        status=EscalationStatus.ESCALATED,
        assigned_to=request.human_reviewer_id or "fraud-review-team",
        message=f"Escalated: {request.reason}"
    )


@app.get("/api/v1/session/{session_id}", tags=["Session"])
async def get_session(session_id: str, current_user: dict = Depends(get_current_user)):
    """Retrieve cached session state from Redis."""
    state = await state_manager.load_state(session_id)
    if not state:
        raise HTTPException(status_code=404, detail=f"Session {session_id} not found or expired")
    return {"session_id": session_id, "state": state}


@app.get("/health", response_model=HealthResponse, tags=["Ops"])
async def health_check():
    """Health check — verifies connectivity to Redis and MCP servers."""
    redis_ok = await state_manager.health_check()
    return HealthResponse(
        status="healthy" if redis_ok else "degraded",
        version=settings.app_version,
        environment=settings.environment,
        services={"redis": "up" if redis_ok else "down", "graph": "up"}
    )
